def test_trigger_audit_lists_exactly_the_hits_with_no_page_change(tmp_path):
    repo, base = git_project(tmp_path)
    append(repo / "crates/a/src/lib.rs", "pub fn hit() {}\n")
    hit = commit(repo, "feat: hit")
    append(repo / "crates/a/src/lib.rs", "pub fn documented() {}\n")
    page = repo / "docs/components/a.md"
    page.write_text(page.read_text().replace("Calls nothing.", "Calls the disk."))
    commit(repo, "feat: documented")
    append(repo / "crates/b/src/lib.rs", "pub fn waived() {}\n")
    commit(repo, "feat: waived\n\nDocs-Unchanged: b: internal")
    append(repo / "crates/a/src/lib.rs", "fn private() {}\n")
    commit(repo, "chore: private")
    r = run(repo, "--trigger-audit", f"{base}..HEAD")
    assert r.returncode == 0
    rows = [ln.split("\t") for ln in r.stdout.splitlines() if ln.strip()]
    assert rows == [[hit, "a", "crates/a/src/lib.rs"]]


