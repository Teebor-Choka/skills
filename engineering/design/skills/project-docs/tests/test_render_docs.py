def test_pr_summary_truncates_an_oversized_block_with_the_count(tmp_path):
    repo, base = git_project(tmp_path)
    body = "".join(f"## Big {i}\n\nPara {i}.\n\n```mermaid\nflowchart TD\n" + "".join(
        f"  N{i}x{j}[node {j}] --> N{i}x{j + 1}\n" for j in range(700)) + "```\n\n" for i in range(5))
    write(repo, "docs/design/big.md", "# big\n\n" + body)
    commit(repo, "docs: big")
    out = run(repo, "--pr-summary", "--base", base).stdout
    assert len(out) <= 60_000
    shown = out.count("```mermaid")
    m = re.search(r"^(\d+) more diagrams in architecture\.md$", out, re.M)
    assert m and 0 < shown < 5 and shown + int(m.group(1)) == 5
    assert "Big 0" in out  # drops from the end


