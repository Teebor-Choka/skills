def test_shuffled_filesystem_order_gives_the_same_output(tmp_path, monkeypatch):
    repo = bare_project(tmp_path)
    write(repo, "docs/design/b.md", "# b\n")
    write(repo, "docs/design/a.md", "# a\n")
    expected = render_docs.render(repo)
    real_walk = os.walk

    def reversed_walk(*args, **kwargs):
        for root, dirs, files in real_walk(*args, **kwargs):
            dirs.reverse()
            files.reverse()
            yield root, dirs, files

    monkeypatch.setattr(os, "walk", reversed_walk)
    assert render_docs.render(repo) == expected


def test_locale_does_not_change_the_output(tmp_path):
    repo = bare_project(tmp_path)
    assert run(repo, env={**GIT_ENV, "LC_ALL": "C"}).returncode == 0
    first = [(repo / ARCH).read_bytes(), (repo / HTML).read_bytes()]
    assert run(repo, env={**GIT_ENV, "LC_ALL": "de_DE.UTF-8"}).returncode == 0
    assert [(repo / ARCH).read_bytes(), (repo / HTML).read_bytes()] == first
    assert first[0].decode() == render_docs.render(repo)[ARCH]


def test_output_has_no_absolute_path_clock_or_crlf(tmp_path):
    repo = bare_project(tmp_path)
    overview = repo / "docs/overview.md"
    overview.write_bytes(overview.read_bytes().replace(b"\n", b"\r\n"))
    out = render_docs.render(repo)
    for text in out.values():
        assert str(tmp_path) not in text
        assert "\r" not in text
        assert text.endswith("\n") and not text.endswith("\n\n")
        assert not re.search(r"generated (at|on)\b|\d{2}:\d{2}:\d{2}", text)
    assert out[ARCH].startswith("<!-- generated by render_docs.py; do not edit -->\n")


