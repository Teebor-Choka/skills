def test_render_time_at_500_docs_and_200_components(tmp_path):
    repo = bare_project(tmp_path, components=())
    for i in range(200):
        write_page(repo, f"c{i:03d}", f"crates/c{i:03d}", (f"c{i - 1:03d}",) if i else ())
    for i in range(300):
        write(repo, f"docs/design/d{i:03d}.md",
              f"# d{i}\n\n## Flow\n\nPara {i}.\n\n```mermaid\nflowchart TD\n  A{i} --> B\n```\n")
    start = time.perf_counter()
    out = render_docs.render(repo)
    elapsed = time.perf_counter() - start
    assert "### c199" in out[ARCH]
    assert elapsed < 3.0, f"{elapsed:.2f}s"
