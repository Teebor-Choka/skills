def git(repo: Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(repo), *args], env=GIT_ENV, capture_output=True, text=True)
    assert r.returncode == 0, f"git {args}: {r.stderr}"
    return r.stdout.strip()


def commit(repo: Path, message: str) -> str:
    git(repo, "add", ".")
    git(repo, "commit", "-q", "-m", message)
    return git(repo, "rev-parse", "HEAD")


def run(repo: Path, *args: str, env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(SCRIPT), str(repo), *args], capture_output=True,
                          text=True, env=env or GIT_ENV, timeout=120)


def bare_project(tmp_path: Path, components=(("Zeta", ()), ("alpha", ()), ("mid", ("Zeta",)),
                                              ("app", ("mid",)))) -> Path:
    """The conformant docs tree plus component pages, no manifests and no git."""
    dest = tmp_path / "bare"
    shutil.copytree(FIXTURES / "conformant", dest)
    for name, deps in components:
        write_page(dest, name, f"crates/{name}", deps)
    return dest


def git_project(tmp_path: Path) -> tuple[Path, str]:
    """A Cargo workspace (a, b depends on a) with pages and committed generated files."""
    dest = tmp_path / "proj"
    shutil.copytree(FIXTURES / "conformant", dest)
    cargo_workspace(dest)
    cargo_member(dest, "a")
    cargo_member(dest, "b", deps=("a",))
    write_page(dest, "a", "crates/a")
    write_page(dest, "b", "crates/b", ("a",))
    git(dest, "init", "-q", "-b", "main")
    assert run(dest).returncode == 0
    return dest, commit(dest, "base")


def append(path: Path, text: str) -> None:
    path.write_text(path.read_text() + text)


def warnings(r: subprocess.CompletedProcess) -> list[str]:
    return [ln for ln in r.stderr.splitlines() if "component-page-stale" in ln]


