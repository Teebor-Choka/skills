def pr_repo(tmp_path: Path, remote: str | None = "git@github.com:acme/widgetd.git") -> tuple[Path, str, str]:
    repo, base = git_project(tmp_path)
    overview = repo / "docs/overview.md"
    overview.write_text(overview.read_text().replace("widgetd --> db[(SQLite)]", "widgetd --> store[(Store)]"))
    run(repo)
    head = commit(repo, "docs: change overview diagram")
    if remote:
        git(repo, "remote", "add", "origin", remote)
    return repo, base, head


def test_pr_summary_links_head_and_shows_only_changed_docs(tmp_path):
    repo, base, head = pr_repo(tmp_path)
    r = run(repo, "--pr-summary", "--base", base)
    assert r.returncode == 0
    link = f"https://github.com/acme/widgetd/blob/{head}/docs/generated/architecture.md"
    assert r.stdout.count(link) == 1
    assert "widgetd --> store[(Store)]" in r.stdout
    assert "docs/overview.md" in r.stdout and "Diagram" in r.stdout
    assert "INSERT" not in r.stdout  # spec.md did not change
    assert "generated by render_docs.py" not in r.stdout  # generated files are excluded
    assert "```mermaid" in r.stdout


